-- ─── Verificación de identidad del vendedor (modelo ER: verificacion_vendedor) ─────────────────────
-- El vendedor sube un documento de identidad; el administrador lo aprueba o lo rechaza con un motivo.
-- Solo un vendedor con una verificación aprobada puede publicar (arquitectura §11, flujo de publicación).
-- documento_url guarda la referencia del archivo en el almacenamiento PRIVADO (no es una URL pública):
-- el documento solo lo ve el administrador por GET /admin/verificaciones/:id/documento.
CREATE TABLE verificacion_vendedor (
  id              INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      INTEGER       NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  tipo_documento  VARCHAR(30)   NOT NULL CHECK (tipo_documento IN ('dpi', 'pasaporte', 'licencia')),
  documento_url   VARCHAR(500)  NOT NULL,
  estado          VARCHAR(20)   NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'aprobada', 'rechazada')),
  revisado_por    INTEGER       REFERENCES usuario(id) ON DELETE SET NULL,
  motivo_rechazo  VARCHAR(300),
  fecha_solicitud TIMESTAMPTZ   NOT NULL DEFAULT now(),
  fecha_revision  TIMESTAMPTZ,
  -- Al rechazar hay que decir por qué; una revisada tiene revisor y fecha
  CONSTRAINT ck_verificacion_rechazo CHECK (estado <> 'rechazada' OR motivo_rechazo IS NOT NULL),
  CONSTRAINT ck_verificacion_revision CHECK (estado = 'pendiente' OR fecha_revision IS NOT NULL)
);
-- Una sola solicitud abierta (pendiente) por vendedor
CREATE UNIQUE INDEX ux_verificacion_pendiente ON verificacion_vendedor(usuario_id) WHERE estado = 'pendiente';
-- Historial por vendedor y cola del administrador
CREATE INDEX verificacion_vendedor_usuario_id_fecha_solicitud_idx ON verificacion_vendedor(usuario_id, fecha_solicitud);
CREATE INDEX verificacion_vendedor_estado_fecha_solicitud_idx ON verificacion_vendedor(estado, fecha_solicitud);
