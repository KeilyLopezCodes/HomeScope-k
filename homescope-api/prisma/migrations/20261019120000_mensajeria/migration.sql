-- ─── Módulo: Comunicación — mensajes y notificaciones (RF-21 a RF-23, §10.3) ──

-- 1. Mensajes de una conversación (comprador ↔ vendedor sobre una propiedad)
CREATE TABLE mensaje (
  id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversacion_id INTEGER        NOT NULL REFERENCES conversacion(id) ON DELETE CASCADE,
  remitente_id    INTEGER        NOT NULL REFERENCES usuario(id),
  contenido       VARCHAR(2000)  NOT NULL CHECK (length(btrim(contenido)) > 0),
  fecha_envio     TIMESTAMPTZ    NOT NULL DEFAULT now(),
  leido_en        TIMESTAMPTZ
);
-- Historial de una conversación (arquitectura §7.4)
CREATE INDEX mensaje_conversacion_id_fecha_envio_idx ON mensaje(conversacion_id, fecha_envio);

-- 2. Notificaciones de cada usuario
CREATE TABLE notificacion (
  id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      INTEGER       NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  tipo            VARCHAR(30)   NOT NULL CHECK (tipo IN ('mensaje', 'visita', 'resena', 'expiracion', 'verificacion', 'sistema')),
  titulo          VARCHAR(150)  NOT NULL,
  contenido       VARCHAR(500)  NOT NULL,
  referencia_tipo VARCHAR(30),
  referencia_id   INTEGER,
  leida           BOOLEAN       NOT NULL DEFAULT FALSE,
  enviada_correo  BOOLEAN       NOT NULL DEFAULT FALSE,
  fecha_creacion  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- Bandeja de notificaciones (arquitectura §7.4)
CREATE INDEX notificacion_usuario_id_leida_fecha_creacion_idx ON notificacion(usuario_id, leida, fecha_creacion);
