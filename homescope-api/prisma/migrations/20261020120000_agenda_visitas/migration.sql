-- ─── Módulo: Agenda — disponibilidad del vendedor y visitas ──────────────────
-- Horas en hora de Guatemala (America/Guatemala, UTC-6)

-- 1. Franjas semanales en que el vendedor puede recibir visitas.
--    propiedad_id NULL = aplica a todas sus propiedades (por ahora es el único caso que usa la API)
CREATE TABLE disponibilidad_vendedor (
  id           INTEGER   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendedor_id  INTEGER   NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  propiedad_id INTEGER   REFERENCES propiedad(id) ON DELETE CASCADE,
  dia_semana   SMALLINT  NOT NULL CHECK (dia_semana BETWEEN 1 AND 7), -- 1 = lunes … 7 = domingo
  hora_inicio  TIME      NOT NULL,
  hora_fin     TIME      NOT NULL,
  activa       BOOLEAN   NOT NULL DEFAULT TRUE,
  CHECK (hora_fin > hora_inicio)
);
CREATE INDEX disponibilidad_vendedor_vendedor_id_idx ON disponibilidad_vendedor(vendedor_id);

-- 2. Visitas solicitadas por un comprador
CREATE TABLE visita (
  id                    INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  propiedad_id          INTEGER       NOT NULL REFERENCES propiedad(id) ON DELETE CASCADE,
  comprador_id          INTEGER       NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  fecha_hora_solicitada TIMESTAMPTZ   NOT NULL,
  fecha_hora_confirmada TIMESTAMPTZ,
  estado                VARCHAR(20)   NOT NULL DEFAULT 'solicitada'
                        CHECK (estado IN ('solicitada', 'confirmada', 'reprogramada', 'cancelada')),
  nota_comprador        VARCHAR(300),
  recordatorio_enviado  BOOLEAN       NOT NULL DEFAULT FALSE,
  fecha_creacion        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  fecha_actualizacion   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX visita_propiedad_id_estado_idx ON visita(propiedad_id, estado);
CREATE INDEX visita_comprador_id_idx ON visita(comprador_id);
-- Recordatorios: visitas confirmadas o reprogramadas próximas y sin recordar
CREATE INDEX visita_recordatorio_idx ON visita(estado, fecha_hora_confirmada) WHERE NOT recordatorio_enviado;
