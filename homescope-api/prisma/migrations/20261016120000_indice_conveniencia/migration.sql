-- 2. Puntos de interés usados en el último cálculo de cada propiedad
CREATE TABLE punto_interes (
  id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  propiedad_id        INTEGER       NOT NULL REFERENCES propiedad(id) ON DELETE CASCADE,
  categoria_id        SMALLINT      NOT NULL REFERENCES categoria_interes(id),
  google_place_id     VARCHAR(200)  NOT NULL,
  nombre              VARCHAR(200)  NOT NULL,
  latitud             NUMERIC(9,6)  NOT NULL,
  longitud            NUMERIC(9,6)  NOT NULL,
  distancia_m         INTEGER       NOT NULL CHECK (distancia_m >= 0),
  tiempo_estimado_min SMALLINT      NOT NULL CHECK (tiempo_estimado_min >= 0),
  radio_consulta_m    SMALLINT      NOT NULL CHECK (radio_consulta_m IN (500, 1000, 2000)),
  fecha_consulta      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX punto_interes_propiedad_id_categoria_id_idx ON punto_interes(propiedad_id, categoria_id);

-- 3. Índice calculado: uno vigente por propiedad, los anteriores quedan como historial
CREATE TABLE indice_conveniencia (
  id                INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  propiedad_id      INTEGER       NOT NULL REFERENCES propiedad(id) ON DELETE CASCADE,
  puntaje_total     NUMERIC(5,2)  NOT NULL CHECK (puntaje_total >= 0 AND puntaje_total <= 100),
  nivel_semaforo    VARCHAR(10)   NOT NULL CHECK (nivel_semaforo IN ('verde', 'amarillo', 'rojo')),
  radio_m           SMALLINT      NOT NULL CHECK (radio_m > 0),
  version_algoritmo VARCHAR(10)   NOT NULL,
  es_vigente        BOOLEAN       NOT NULL DEFAULT TRUE,
  fecha_calculo     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX indice_conveniencia_propiedad_id_idx ON indice_conveniencia(propiedad_id);
CREATE INDEX indice_conveniencia_es_vigente_puntaje_total_idx ON indice_conveniencia(es_vigente, puntaje_total);
-- Un solo índice vigente por propiedad (Prisma no expresa índices parciales)
CREATE UNIQUE INDEX ux_indice_vigente ON indice_conveniencia(propiedad_id) WHERE es_vigente;

-- 4. Subpuntaje de cada categoría dentro de un índice
CREATE TABLE sub_puntaje_categoria (
  indice_id          INTEGER       NOT NULL REFERENCES indice_conveniencia(id) ON DELETE CASCADE,
  categoria_id       SMALLINT      NOT NULL REFERENCES categoria_interes(id),
  puntaje            NUMERIC(5,2)  NOT NULL CHECK (puntaje >= 0 AND puntaje <= 100),
  cantidad_puntos    SMALLINT      NOT NULL CHECK (cantidad_puntos >= 0),
  distancia_minima_m INTEGER       CHECK (distancia_minima_m >= 0),
  PRIMARY KEY (indice_id, categoria_id)
);
