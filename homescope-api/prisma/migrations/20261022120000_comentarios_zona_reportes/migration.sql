-- ─── Reputación: comentarios sobre la zona de una propiedad ──────────────────
CREATE TABLE comentario_zona (
  id             INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  propiedad_id   INTEGER        NOT NULL REFERENCES propiedad(id) ON DELETE CASCADE,
  usuario_id     INTEGER        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  comentario     VARCHAR(1000)  NOT NULL CHECK (length(btrim(comentario)) > 0),
  estado         VARCHAR(10)    NOT NULL DEFAULT 'visible' CHECK (estado IN ('visible', 'oculto')),
  fecha_creacion TIMESTAMPTZ    NOT NULL DEFAULT now(),
  -- Un comentario por persona y propiedad
  CONSTRAINT ux_comentario_zona UNIQUE (propiedad_id, usuario_id)
);
CREATE INDEX comentario_zona_propiedad_id_estado_fecha_creacion_idx ON comentario_zona(propiedad_id, estado, fecha_creacion);

-- ─── Moderación: reportes de usuarios ────────────────────────────────────────
-- Genérico (propiedad | usuario | comentario) según el modelo; la API por ahora reporta comentarios de zona
CREATE TABLE reporte (
  id                   INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reportante_id        INTEGER        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  tipo_objetivo        VARCHAR(20)    NOT NULL CHECK (tipo_objetivo IN ('propiedad', 'usuario', 'comentario')),
  propiedad_id         INTEGER        REFERENCES propiedad(id) ON DELETE CASCADE,
  usuario_reportado_id INTEGER        REFERENCES usuario(id) ON DELETE CASCADE,
  comentario_zona_id   INTEGER        REFERENCES comentario_zona(id) ON DELETE CASCADE,
  motivo               VARCHAR(50)    NOT NULL,
  descripcion          VARCHAR(1000),
  estado               VARCHAR(20)    NOT NULL DEFAULT 'pendiente'
                       CHECK (estado IN ('pendiente', 'en_revision', 'resuelto', 'descartado')),
  fecha_creacion       TIMESTAMPTZ    NOT NULL DEFAULT now(),
  -- El objetivo indicado por tipo_objetivo debe venir informado
  CONSTRAINT ck_reporte_objetivo CHECK (
    (tipo_objetivo = 'comentario' AND comentario_zona_id IS NOT NULL) OR
    (tipo_objetivo = 'propiedad'  AND propiedad_id IS NOT NULL) OR
    (tipo_objetivo = 'usuario'    AND usuario_reportado_id IS NOT NULL)
  )
);
-- Cola del administrador
CREATE INDEX reporte_estado_fecha_creacion_idx ON reporte(estado, fecha_creacion);
-- Un mismo usuario no reporta dos veces el mismo comentario mientras el reporte esté abierto
CREATE UNIQUE INDEX ux_reporte_comentario_abierto ON reporte(reportante_id, comentario_zona_id)
  WHERE comentario_zona_id IS NOT NULL AND estado IN ('pendiente', 'en_revision');
