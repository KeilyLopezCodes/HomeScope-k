-- ─── Módulo: Reputación — reseñas y calificaciones de vendedores (RF-30) ──────

CREATE TABLE resena (
  id             INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendedor_id    INTEGER        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  comprador_id   INTEGER        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  propiedad_id   INTEGER        NOT NULL REFERENCES propiedad(id) ON DELETE CASCADE,
  calificacion   SMALLINT       NOT NULL,
  comentario     VARCHAR(1000),
  fecha_creacion TIMESTAMPTZ    NOT NULL DEFAULT now(),
  -- Arquitectura §7.3: una reseña por comprador y propiedad, calificación de 1 a 5
  CONSTRAINT ux_resena UNIQUE (comprador_id, propiedad_id),
  CONSTRAINT ck_calificacion CHECK (calificacion BETWEEN 1 AND 5),
  CONSTRAINT ck_resena_no_propia CHECK (vendedor_id <> comprador_id)
);
-- Perfil del vendedor: promedio y listado de sus reseñas
CREATE INDEX resena_vendedor_id_fecha_creacion_idx ON resena(vendedor_id, fecha_creacion);
