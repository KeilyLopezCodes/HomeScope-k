-- ─── Moderación: registro de las acciones del administrador (modelo ER: accion_moderacion) ──────────
-- Cada acción (aprobar, pausar o eliminar una publicación; aprobar, suspender o reactivar una cuenta;
-- ocultar un comentario o descartar un reporte) queda registrada con quién la hizo, sobre qué y por qué.
-- Las referencias pasan a NULL si el objetivo se borra (una publicación eliminada por moderación):
-- `detalle` guarda una copia de lo necesario para que el registro siga siendo legible.
CREATE TABLE accion_moderacion (
  id               INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  administrador_id INTEGER       NOT NULL REFERENCES usuario(id),
  reporte_id       INTEGER       REFERENCES reporte(id) ON DELETE SET NULL,
  accion           VARCHAR(20)   NOT NULL CHECK (accion IN (
                     'aprobar', 'pausar', 'eliminar', 'suspender', 'reactivar', 'ocultar_comentario', 'descartar_reporte'
                   )),
  propiedad_id     INTEGER       REFERENCES propiedad(id) ON DELETE SET NULL,
  usuario_id       INTEGER       REFERENCES usuario(id) ON DELETE SET NULL,
  motivo           VARCHAR(300)  NOT NULL,
  detalle          JSONB,
  fecha_accion     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- Historial por publicación, por usuario y general (lo más reciente primero)
CREATE INDEX accion_moderacion_propiedad_id_fecha_accion_idx ON accion_moderacion(propiedad_id, fecha_accion);
CREATE INDEX accion_moderacion_usuario_id_fecha_accion_idx   ON accion_moderacion(usuario_id, fecha_accion);
CREATE INDEX accion_moderacion_fecha_accion_idx              ON accion_moderacion(fecha_accion);

-- Reportes de publicaciones y de usuarios: igual que con los comentarios, un usuario no reporta dos
-- veces lo mismo mientras su reporte siga abierto
CREATE UNIQUE INDEX ux_reporte_propiedad_abierto ON reporte(reportante_id, propiedad_id)
  WHERE propiedad_id IS NOT NULL AND estado IN ('pendiente', 'en_revision');
CREATE UNIQUE INDEX ux_reporte_usuario_abierto ON reporte(reportante_id, usuario_reportado_id)
  WHERE usuario_reportado_id IS NOT NULL AND estado IN ('pendiente', 'en_revision');
-- Cola por objetivo (publicaciones y usuarios reportados)
CREATE INDEX reporte_propiedad_id_estado_idx ON reporte(propiedad_id, estado) WHERE propiedad_id IS NOT NULL;
CREATE INDEX reporte_usuario_reportado_id_estado_idx ON reporte(usuario_reportado_id, estado) WHERE usuario_reportado_id IS NOT NULL;
